"""Что уедет на полку, если выложить эту систему.

Перед тем как класть свою систему в открытый доступ, надо посмотреть глазами, что именно
уезжает. Система — уезжает. Ваши данные, ключи и документы — остаются дома. Перепутать эти
две вещи можно ровно один раз: выложенное в открытый репозиторий остаётся в его истории,
даже если файл потом удалить.

Скрипт показывает список и отдельно — то, что похоже на личное.

Запуск:
    .venv/bin/python scripts/что_уедет.py             # для этой системы
    .venv/bin/python scripts/что_уедет.py ~/NeuroCombine/«Финансовый помощник»
    .venv/bin/python scripts/что_уедет.py <папка> --закрыть   # дописать находки в .gitignore
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

# Имена и куски имён, за которыми обычно стоят личные данные
ОПАСНЫЕ_ИМЕНА = [
    ("выписк", "банковская выписка"),
    ("чек", "чеки"),
    ("отчёт", "готовые отчёты с вашими цифрами"),
    ("отчет", "готовые отчёты с вашими цифрами"),
    ("данные", "папка с данными"),
    ("ключ", "ключи доступа"),
    ("token", "токен доступа"),
    ("secret", "секрет"),
    ("credential", "учётные данные"),
    ("passw", "пароль"),
    ("cookie", "куки браузера"),
    (r"\bauth\b", "данные входа"),   # именно слово: «author» — не про это
    ("профил", "профиль с вашими данными"),
    ("паспорт", "персональные документы"),
    ("договор", "документы"),
    ("клиент", "данные клиентов"),
]
ОПАСНЫЕ_РАСШИРЕНИЯ = {
    ".csv": "таблица с данными",
    ".xlsx": "таблица с данными",
    ".xls": "таблица с данными",
    ".ofx": "выгрузка из банка",
    ".qif": "выгрузка из банка",
    ".db": "база данных",
    ".sqlite": "база данных",
    ".sqlite3": "база данных",
    ".pdf": "документ (проверьте, чей)",
    ".env": "файл с ключами",
    ".pem": "ключ",
    ".key": "ключ",
    ".p12": "сертификат",
    ".mp4": "запись (может быть личной)",
    ".mov": "запись (может быть личной)",
    ".m4a": "запись голоса",
    ".mp3": "запись голоса",
}
# Похоже на ключ доступа внутри файла
ПОХОЖЕ_НА_КЛЮЧ = re.compile(
    r"(sk-[A-Za-z0-9_\-]{16,}|ghp_[A-Za-z0-9]{20,}|AIza[A-Za-z0-9_\-]{20,}|"
    r"[A-Za-z0-9_\-]{0,20}(api[_\-]?key|token|secret)[\"'\s:=]+[A-Za-z0-9_\-]{16,})",
    re.I,
)
ТЕКСТОВЫЕ = {".md", ".txt", ".json", ".toml", ".yaml", ".yml", ".py", ".sh", ".html", ".css", ".js"}

# Учебное и образцы — часть системы, они как раз ЕДУТ. Иначе ученик закроет то,
# на чём другой человек будет пробовать систему в первый раз.
УЧЕБНОЕ = ("демо", "demo", "учебн", "образец", "образцы", "пример", "sample", "шаблон", "_шаблон", "test")


def файлы_под_git(папка):
    """Что реально уедет: git показывает это точнее любых догадок."""
    try:
        готово = subprocess.run(
            ["git", "-C", str(папка), "ls-files"], capture_output=True, text=True, check=True
        )
        return [папка / с for с in готово.stdout.split("\n") if с.strip()], True
    except Exception:
        файлы = [
            п for п in папка.rglob("*")
            if п.is_file() and ".git" not in п.parts and "__pycache__" not in п.parts
        ]
        return файлы, False


def чем_опасен(путь, корень):
    относительный = str(путь.relative_to(корень)).lower()
    if any(у in относительный for у in УЧЕБНОЕ):
        return []          # учебные данные и образцы уезжают вместе с системой — так и надо
    причины = []
    for кусок, что_это in ОПАСНЫЕ_ИМЕНА:
        совпало = re.search(кусок, относительный) if кусок.startswith(r"\b") else (кусок in относительный)
        if совпало:
            причины.append(что_это)
            break
    подпись = ОПАСНЫЕ_РАСШИРЕНИЯ.get(путь.suffix.lower())
    if подпись:
        причины.append(подпись)
    if путь.suffix.lower() in ТЕКСТОВЫЕ and путь.stat().st_size < 2_000_000:
        try:
            if ПОХОЖЕ_НА_КЛЮЧ.search(путь.read_text(encoding="utf-8", errors="ignore")):
                причины.append("⚠️ внутри похоже на ключ доступа")
        except Exception:
            pass
    return причины


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("папка", nargs="?", default=".", help="папка системы, которую собираетесь выложить")
    ap.add_argument("--закрыть", action="store_true", help="дописать находки в .gitignore")
    args = ap.parse_args()

    корень = Path(args.папка).expanduser().resolve()
    if not корень.exists():
        print(f"\n⛔ Нет такой папки: {корень}\n")
        sys.exit(1)

    файлы, под_git = файлы_под_git(корень)
    if not файлы:
        print("В папке нечего выкладывать — файлов не нашлось.")
        return

    подозрительные = []
    for ф in файлы:
        причины = чем_опасен(ф, корень)
        if причины:
            подозрительные.append((ф.relative_to(корень), причины))

    print(f"Папка: {корень}")
    print(f"Уедет файлов: {len(файлы)}" + ("" if под_git else "  (git ещё не заведён — считаю все)"))
    print()

    if not подозрительные:
        print("✅ Ничего похожего на личное не нашлось.")
        print("   Всё равно пролистайте список глазами: машина ищет по именам и расширениям,")
        print("   а ваши данные могут лежать в файле с любым названием.")
        return

    print(f"⚠️  Похоже на личное — {len(подозрительные)} шт. Это НЕ должно уезжать на полку:\n")
    for путь, причины in подозрительные[:60]:
        print(f"   {путь}")
        print(f"      ← {', '.join(причины)}")
    if len(подозрительные) > 60:
        print(f"   … и ещё {len(подозрительные) - 60}")

    правила = sorted({
        (str(п.parent) + "/") if str(п.parent) != "." else п.name for п, _ in подозрительные
    })
    print("\nЧто добавить в `.gitignore`, чтобы это осталось дома:\n")
    for п in правила:
        print(f"   {п}")

    if args.закрыть:
        файл = корень / ".gitignore"
        было = файл.read_text(encoding="utf-8") if файл.exists() else ""
        новые = [п for п in правила if п not in было]
        if новые:
            файл.write_text(
                было.rstrip("\n") + "\n\n# Личное — на полку не уезжает (scripts/что_уедет.py)\n"
                + "\n".join(новые) + "\n",
                encoding="utf-8",
            )
            print(f"\n✅ Дописано в .gitignore правил: {len(новые)}")
            print("   Проверьте ещё раз: .venv/bin/python scripts/что_уедет.py")
        else:
            print("\n.gitignore уже всё это закрывает.")
    else:
        print("\nДописать автоматически: добавьте к команде --закрыть")
        print("⛔ Уже выложенное не лечится удалением файла: он остаётся в истории.")
        print("   Если личное уже уехало — репозиторий надо удалить и создать заново.")


if __name__ == "__main__":
    main()
